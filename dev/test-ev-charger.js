/* EV charger and distribution board regression checks. */
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context={};vm.createContext(context);
for(const f of ['src/ha-state.js','src/readout-scale.js','src/svg-template.js','src/ev-charger.js','src/distribution-board.js'])
 vm.runInContext(fs.readFileSync(f,'utf8'),context,{filename:f});
const svg=file=>fs.readFileSync('src/icons/'+file+'.svg','utf8').replace(/^\s*<svg\b[^>]*>/,'').replace(/<\/svg>\s*$/,'');
context.evArt=svg('ev-charger');context.boardArt=svg('distribution-board');
vm.runInContext('this.HASSStudioIconTemplates={evCharger:this.evArt,distributionBoard:this.boardArt};this.ev=HASSStudioEVCharger;this.board=HASSStudioDistributionBoard;',context);
const charger=context.ev,board=context.board;
const value=(state,unit='')=>({state:String(state),attributes:{unit_of_measurement:unit}});
const node=(options={})=>({id:'ev-test',type:'ev_charger',ev_charger:options});
assert.equal(charger.normalize(node()).phases,3);
assert.equal(charger.normalize(node({phases:1})).phases,1);
assert.equal(charger.data(node(),{states:{}}).status,'unknown');
const h={states:{'sensor.p':value(7200,'W'),'sensor.session':value(14500,'Wh'),'sensor.l1':value(230,'V'),'sensor.a1':value(15,'A'),'sensor.total':value(12.4,'MWh'),'sensor.state':value('charging'),'binary_sensor.fault':value('off')}};
const wired=node({entities:{power:'sensor.p',session_energy:'sensor.session',total_energy:'sensor.total',voltage_l1:'sensor.l1',current_l1:'sensor.a1',status:'sensor.state',alarm:'binary_sensor.fault'}});
const live=charger.data(wired,h);
assert.equal(live.power,7.2);assert.equal(live.session,14.5);
assert.equal(live.diagnostics.total_energy,12400);
assert.equal(live.status,'charging');
const running=charger.render(wired,h);
assert.match(running,/7\.2 kW/);assert.match(running,/14\.5 kWh/);assert.match(running,/ss-ev-charging/);
const stopped=charger.render(wired,{states:{...h.states,'sensor.p':value(0,'W'),'sensor.state':value('ready')}});
assert.doesNotMatch(stopped,/class="ss-ev-charging"/);
assert.match(stopped,/id="ssevev-test-ev-led"[^>]*fill="#f5a438"/);
const bad=charger.render(wired,{states:{...h.states,'binary_sensor.fault':value('on')}});
assert.match(bad,/id="ssevev-test-ev-alarm" visibility="visible"/);
assert.match(bad,/id="ssevev-test-ev-led"[^>]*fill="#ec4848"/);
const offline=charger.render(wired,{states:{}});
assert.match(offline,/id="ssevev-test-ev-power-text"[^>]*>—<\/text>/);
const manual=charger.data(node({mode:'manual',manual:{power:3.6,session_energy:2.4,status:'charging'}}),null);
assert.equal(manual.power,3.6);
assert.equal(manual.session,2.4);
const extended=charger.render(node({phases:1,show_extra:true,mode:'manual'}),null);
assert.match(extended,/ŁADOWARKA EV/);
assert(!extended.includes('L2 napięcie'));assert(!extended.includes('L3 prąd'));
const two=board.render({id:'board1'});
assert.match(two,/ssdistributionboard1-distribution-breakers/);
assert.match(two,/ssdistributionboard1-distribution-meter/);
assert.equal(board.geometry().width,150);
console.log('OK: EV AC power, session energy, 1/3 phases, status/alarm, distribution SVG.');
